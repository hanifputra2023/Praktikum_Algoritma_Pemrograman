#Operasi Aritmatika

a = 10
b = 3

#Operasi Penjumlahan
hasil = a + b
print(a, "+", b, "=", hasil)

#Operasi Pengurangan
hasil = a - b
print(a, "-", b, "=", hasil)

#Operasi Perkalian
hasil = a * b
print(a, "*", b, "=", hasil)

#Operasi Pembagian
hasil = a / b
print(a, "/", b, "=", hasil)

#Operasi Modulus
hasil = a % b
print(a, "%", b, "=", hasil)

#Operasi Eksponen
hasil = a ** b
print(a, "**", b, "=", hasil)

#Operasi Floor Division
hasil = a // b
print(a, "//", b, "=", hasil)

