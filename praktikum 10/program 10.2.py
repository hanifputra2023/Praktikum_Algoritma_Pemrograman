## Dictionary

# list → array, mengakses dengan menggunakan index

data_list = ['ucup', 'rendi', 'salsa']
print(data_list[0])

# dictionary (dict) → associative array
# identifier → key

data_dict = {
    'key': 'value',
    'cp': 'ucup',
    'rd': 'rendi',
    'sl': 'salsa',
    'nmbr': 100,
    'list': data_list
}

print(data_dict)
print(data_dict['cp'])
print(data_dict['nmbr']) 
print(data_dict['list']) 